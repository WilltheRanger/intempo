/**
 * Regenerates `src/data/licences.ts` from what's actually installed.
 *
 * Direct dependencies only — the full transitive tree runs to hundreds of
 * packages and nobody reads it. Run after changing dependencies:
 *
 *   node scripts/generate-licences.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const names = Object.keys({ ...pkg.dependencies, ...pkg.devDependencies }).sort();

/**
 * Things the app ships that npm does not know about.
 *
 * Bravura is a font file checked into `assets/fonts`, subset in-repo by
 * `tools/subset-bravura.py`. It is redistributed under the SIL Open Font
 * License, which requires the notice — and a licence page that lists every
 * MIT package while omitting the one file with an attribution requirement
 * would be exactly backwards.
 */
const VENDORED = [
  { name: 'Bravura (music font)', version: 'subset', licence: 'OFL-1.1' },
];

const entries = names.flatMap((name) => {
  let manifest;
  try {
    manifest = JSON.parse(
      readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'),
    );
  } catch {
    return [];
  }
  const licence =
    typeof manifest.license === 'string'
      ? manifest.license
      : manifest.license?.type ?? 'See package';
  return [{ name, version: manifest.version, licence }];
});

const body = [...entries, ...VENDORED]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(
    (e) =>
      `  { name: '${e.name}', version: '${e.version}', licence: '${e.licence}' },`,
  )
  .join('\n');

writeFileSync(
  join(root, 'src/data/licences.ts'),
  `/**
 * Open-source packages InTempo is built on.
 *
 * Generated by \`scripts/generate-licences.mjs\` from the installed tree — do
 * not edit by hand, and re-run it after changing dependencies. Direct
 * dependencies only: the transitive tree is hundreds of packages and nobody
 * reads it.
 */
export interface Licence {
  name: string;
  version: string;
  licence: string;
}

export const LICENCES: Licence[] = [
${body}
];
`,
);

console.log(`wrote ${entries.length} entries`);
